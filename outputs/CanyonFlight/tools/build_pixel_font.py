for ch, rows in G.items():
    assert len(rows) in (7, 9), ch
    assert len({len(r) for r in rows}) == 1, ch
    assert all(set(r) <= {'#', '.'} for r in rows), ch

out = ['/* Generated by tools/build_pixel_font.py: original 3DMicroFlight 5x7',
       '   proportional pixel font. Glyphs for ASCII 32..126; width 0 = none. */',
       '#define PF_FIRST 32', '#define PF_COUNT 95', '#define PF_ROWS 9',
       'static const unsigned char pfWidth[PF_COUNT]={']
widths, rows = [], []
for code in range(32, 127):
    r = G.get(chr(code))
    widths.append(len(r[0]) if r else 0)
    bits = []
    for y in range(9):
        line = r[y] if r and y < len(r) else ''
        bits.append(sum(1 << x for x, c in enumerate(line) if c == '#'))
    rows.append(bits)
out.append(','.join(map(str, widths)) + '};')
out.append('static const unsigned char pfRows[PF_COUNT][PF_ROWS]={')
out.append(',\n'.join('{' + ','.join(map(str, b)) + '}' for b in rows) + '};')
path = Path(__file__).resolve().parent.parent / 'include' / 'pixel_font_glyphs.h'
path.write_text('\n'.join(out) + '\n')
print('glyphs', sum(1 for w in widths if w), '->', path)
